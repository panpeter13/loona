const { mainKeyboard } = require("../keyboards/mainKeyboard");
const { getOrCreateUser } = require("../services/userService");

function registerStartHandler(bot) {
  bot.start(async (ctx) => {
    const user = await getOrCreateUser(ctx.from.id);

    if (!user) {
      return ctx.reply("Не получилось создать профиль. Попробуйте позже.");
    }

    return ctx.reply(
      "Привет. Я LOONA 🌙\n\n" +
        "Я помогу отслеживать цикл анонимно.\n\n" +
        "Важно: прогнозы примерные и не являются медицинской рекомендацией.",
      mainKeyboard,
    );
  });

  bot.hears("❓ Помощь", (ctx) => {
    return ctx.reply(
      `LOONA умеет:\n\n` +
        `🌙 Начался цикл — записать начало сегодня\n` +
        `✅ Завершился — записать окончание сегодня\n` +
        `✍️ Указать дату начала — выбрать дату через календарь\n` +
        `✍️ Указать дату окончания — выбрать дату через календарь\n` +
        `✨ Главный экран — текущий статус цикла\n` +
        `📅 Мой цикл — прогноз следующего периода и овуляции\n` +
        `💕 Цикл партнёрши — просмотр прогноза партнёрши\n` +
        `👤 Режим — свой цикл или режим партнёра\n` +
        `⚙️ Настройки — длина цикла и периода\n` +
        `↩️ Отменить последнюю запись — исправить ошибку\n` +
        `🗑 Удалить мои данные — полное удаление\n\n` +
        `🔒 Для работы уведомлений хранится Telegram ID и обезличенный хэш пользователя.\n` +
        `Личные данные не передаются третьим лицам.`,
    );
  });
}

module.exports = registerStartHandler;
